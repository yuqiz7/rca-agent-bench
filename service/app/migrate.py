#!/usr/bin/env python3
"""migrate.py -- apply service/migrations/*.sql in filename order, once each.

WHY THIS AND NOT ALEMBIC (决策 037, item 2)
-------------------------------------------
Alembic earns its keep on long-lived, multi-branch, multi-author schemas where
autogenerated diffs beat hand-written DDL. This is six tables, one author, and a
v1 that will almost certainly only add columns. What Alembic would cost here is
real: a dependency, an env.py, autogenerate false positives, and a new failure
mode where the model definitions and the migrations disagree. The whole runner is
below, and it is shorter than that env.py would be.

The ledger is `schema_migrations(version, applied_at)`, keyed by FILENAME. Each
file applies inside its own transaction together with its ledger row, so a
migration that fails halfway leaves neither the DDL nor the claim that it ran --
Postgres is one of the few databases where that is true of DDL as well as DML,
and it is why "rerun after a crash" needs no repair step here.
"""
import pathlib

MIGRATIONS_DIR = pathlib.Path(__file__).resolve().parent.parent / "migrations"

# Also declared in 001_init.sql; see the comment there. IF NOT EXISTS on both
# sides makes whichever runs second a no-op.
LEDGER_DDL = """
CREATE TABLE IF NOT EXISTS schema_migrations (
  version    text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
)
"""


def apply_pending(conn, migrations_dir: pathlib.Path = MIGRATIONS_DIR) -> list[str]:
    """Apply every *.sql not yet in schema_migrations. Returns what it applied."""
    with conn.transaction(), conn.cursor() as cur:
        cur.execute(LEDGER_DDL)
        cur.execute("SELECT version FROM schema_migrations")
        already = {row[0] for row in cur.fetchall()}

    applied = []
    for path in sorted(migrations_dir.glob("*.sql")):
        if path.name in already:
            continue
        with conn.transaction(), conn.cursor() as cur:
            cur.execute(path.read_text(encoding="utf-8"))
            cur.execute("INSERT INTO schema_migrations (version) VALUES (%s)", (path.name,))
        applied.append(path.name)
    return applied
